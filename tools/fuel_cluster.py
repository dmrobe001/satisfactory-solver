#!/usr/bin/env python3
"""Whole-machine fuel clusters on five recipes (exact fractions).

  Heavy Oil Residue (alt)  30 oil -> 40 residue + 20 polymer resin
  Diluted Fuel             50 residue + 100 water -> 100 fuel
  Nitro Rocket Fuel        100 fuel + 75 nitrogen + 100 sulfur + 50 coal -> 150 rocket fuel + 25 compacted coal
  Turbofuel                22.5 fuel + 15 compacted coal -> 18.75 turbofuel
  Ionized Fuel             40 rocket fuel + 2.5 power shards -> 40 ionized fuel + 5 compacted coal

Rules: every one of the first four at whole machines and 100 %.  One Turbofuel
refinery feeds exactly one generator at 250 % (18.75/min, 625 MW).  Fuel that is
left over goes to plain fuel generators (20/min each) or a Packaged Fuel packager at
25, 50 or 100 %.  Every fluid nets exactly 0.  Compacted coal must cover the
Turbofuel refineries; the rest is spare (Fine Black Powder takes 15/min).

The small draws on rocket fuel (--ionized, --packed-rocket, per minute) come out of
one rocket-fuel generator, the only one below 100 %: a generator burns 25/6 per
minute, so with x drawn elsewhere it runs at 1 - 0.24 x, which the game can set
exactly whenever x is a terminating decimal.

Usage: python3 tools/fuel_cluster.py [--max-nitro 12] [--base 24600]
--base: MW generated elsewhere (4 + 2 + 1 nuclear plants and 31 geysers = 24,600).
"""
import argparse
from fractions import Fraction as F


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--max-nitro", type=int, default=12)
    ap.add_argument("--ionized", type=F, default=F(1), help="rocket fuel per minute turned into ionized fuel")
    ap.add_argument("--packed-rocket", type=F, default=F(3, 2), help="rocket fuel per minute packaged")
    ap.add_argument("--base", type=float, default=24600.0)
    a = ap.parse_args()
    x = a.ionized + a.packed_rocket
    trim = 1 - F(6, 25) * x
    print("small draws: Ionized Fuel refinery at %s %% (%s ionized/min, %s shards/min), Packaged Ionized Fuel at %s %% (%s/min),"
          % (float(a.ionized / 40 * 100), float(a.ionized), float(a.ionized / 16), float(a.ionized / 80 * 100), float(a.ionized / 2)))
    print("             Packaged Rocket Fuel at %s %% (%s/min); one rocket generator at %s %%\n"
          % (float(a.packed_rocket / 120 * 100), float(a.packed_rocket / 2), float(trim * 100)))
    print("%3s %3s %3s %3s %4s %5s | %5s %5s %5s %5s %5s | %5s %6s | %7s %8s  fuel left over"
          % ("HOR", "Dil", "Nit", "Tur", "RktG", "TurG", "oil", "water", "N2", "S", "coal", "resin", "CCspare", "MW", "MW total"))
    for n in range(1, a.max_nitro + 1):
        for t in range(0, 25, 4):
            if 15 * t > 25 * n:
                continue
            for d in range(n, 2 * n + 8):
                left = 100 * d - 100 * n - F(45, 2) * t      # fuel for generators or packaging
                if left < 0 or (50 * d) % 40:
                    continue
                h = 50 * d // 40
                for pf in (F(0), F(1, 4), F(1, 2), F(1)):
                    gf = (left - 40 * pf) / 20
                    if gf < 0 or gf.denominator != 1 or gf > 6:
                        continue
                    gens = F(150 * n, 1) / F(25, 6)            # rocket generators' worth of fuel
                    if gens.denominator != 1:
                        continue
                    mw = (gens - 1 + trim) * 250 + t * 625 + gf * 250
                    own = h * 30 + d * 75 + n * 75 + t * 30
                    total = 1.3 * (a.base + float(mw)) + 500
                    extra = ", ".join(s for s in ("%d fuel generator%s" % (gf, "s" * (gf != 1)) if gf else "",
                                                  "Packaged Fuel at %g %% (%g/min)" % (pf * 100, 40 * pf) if pf else "") if s) or "none"
                    print("%3d %3d %3d %3d %4s %5d | %5d %5d %5g %5d %5d | %5d %6g | %7.0f %8.0f  %s"
                          % (h, d, n, t, "%d+1" % (gens - 1), t, 30 * h, 100 * d, 75 * n, 100 * n, 50 * n, 20 * h,
                             float(25 * n - 15 * t + a.ionized / 8), float(mw), total, extra))
    print("\nMW: generated by the cluster (its own machines draw about 2 % of it).  MW total: 1.3 x (base + MW) + 500.")


# ---- munitions add-on for the 5 / 4 / 3 / 4 block --------------------------------
# (machines, clock %, recipe, {item: per minute at 100 %; + made, - used})
MUNITIONS = [
    (1, "20", "Explosive Rebar", {"Explosive Rebar": 5, "Smokeless Powder": -10}),
    (1, "20", "Cluster Nobelisk", {"Cluster Nobelisk": F(5, 2), "Nobelisk": F(-15, 2), "Smokeless Powder": -10}),
    (1, "25", "Nuke Nobelisk", {"Nuke Nobelisk": F(1, 2), "Nobelisk": F(-5, 2), "Smokeless Powder": -5}),
    (1, "25", "Rifle Ammo", {"Rifle Ammo": 75, "Smokeless Powder": -10}),
    (1, "4", "Turbo Rifle Ammo (Blender)", {"Turbo Rifle Ammo": 250, "Rifle Ammo": -125, "Turbofuel": -15}),
    (1, "10", "Homing Rifle Ammo", {"Homing Rifle Ammo": 25, "Rifle Ammo": -50}),
    (1, "25", "Nobelisk", {"Nobelisk": 10, "Black Powder": -20}),
    (1, "40", "Smokeless Powder", {"Smokeless Powder": 20, "Black Powder": -20, "Heavy Oil Residue": -10}),
    (1, "30", "Fine Black Powder", {"Black Powder": 45, "Compacted Coal": -15, "Sulfur": F(-15, 2)}),
    (1, "4", "Gas Filter", {"Gas Filter": F(15, 2), "Fabric": -15, "Coal": -30}),
    (1, "2", "Polyester Fabric", {"Fabric": 30, "Polymer Resin": -30, "Water": -30}),
    (1, "1.5", "Packaged Turbofuel", {"Packaged Turbofuel": 20, "Turbofuel": -20}),
    # what feeds the fluids those draw, so the block's own machines and generators are untouched
    (1, "10", "Heavy Oil Residue (6th refinery)", {"Heavy Oil Residue": 40, "Polymer Resin": 20, "Crude Oil": -30}),
    (1, "4.8", "Turbofuel (5th refinery)", {"Turbofuel": F(75, 4), "Fuel": F(-45, 2), "Compacted Coal": -15}),
    (1, "-2.7", "Packaged Fuel (22.3 % instead of 25 %)", {"Packaged Fuel": 40, "Fuel": -40}),
]


def munitions():
    """Net flows of the add-on; the three fluids must come out at exactly 0."""
    net = {}
    print("\nMunitions add-on to the 5 / 4 / 3 / 4 block:")
    for n, c, name, flow in MUNITIONS:
        lvl = n * F(c) / 100
        print("  %d x %5s %%  %s" % (n, c, name))
        for k, q in flow.items():
            net[k] = net.get(k, 0) + q * lvl
    for k in ("Heavy Oil Residue", "Turbofuel", "Fuel"):
        assert net[k] == 0, (k, net[k])
    print("  fluids (Heavy Oil Residue, Turbofuel, Fuel): net exactly 0")
    print("  net per minute: " + ", ".join("%s %+g" % (k, float(v)) for k, v in sorted(net.items()) if v))


if __name__ == "__main__":
    main()
    munitions()
